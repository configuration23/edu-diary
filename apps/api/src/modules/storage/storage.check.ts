import type { StorageAdapter } from './storage.adapter';
import { objectKey } from './storage.adapter';

/**
 * Проверка подключения к хранилищу.
 *
 * Администратору нужна не догадка, а факт: «настройки сохранены, но файлы не грузятся» —
 * худший вариант, потому что причина неизвестна. Поэтому проверка **пишет настоящий файл**,
 * читает его обратно и удаляет: так проверяются и права на запись, и права на чтение, а не
 * только доступность сервера.
 *
 * Работает **одинаково для `local` и `s3`**: и то и другое скрыто за одним интерфейсом, и
 * проверка не знает, куда пишет. Это и есть смысл абстракции — переключение хранилища не
 * требует отдельной проверки под каждый вариант. Кнопка в интерфейсе одна и меняет поведение
 * вслед за выбранным типом.
 *
 * Разница только в том, **что означает отказ**: у локального каталога это чаще всего
 * отсутствующий путь или права, у S3 — адрес, bucket или ключи. Поэтому в ответе есть
 * `checked` и разные формулировки — чтобы администратор понимал, где искать.
 *
 * Пробный файл создаётся под случайным ключом и **удаляется за собой**: в рабочем хранилище
 * не остаётся мусора от проверок.
 */

export interface ConnectionTestResult {
  ok: boolean;
  /** Шаг, на котором остановились: до него всё работало. */
  step: 'health' | 'write' | 'read' | 'remove' | 'done';
  /** Понятное объяснение для человека. */
  message: string;
  /**
   * Что делать. Не «произошла ошибка», а следующее действие: администратор читает именно эту
   * строку, когда файлы не грузятся.
   */
  hint: string;
  /** Техническая подробность для разбора: текст ошибки хранилища. */
  detail: string | null;
  /** Что именно проверили: «локальный каталог» или «внешнее хранилище (S3)». */
  checked: string;
}

export async function testStorageConnection(
  adapter: StorageAdapter,
): Promise<ConnectionTestResult> {
  const isS3 = adapter.kind === 's3';
  const checked = isS3 ? 'внешнее хранилище (S3)' : 'локальный каталог';

  const health = await adapter.health();
  if (!health.ok) {
    return {
      ok: false,
      step: 'health',
      message: isS3
        ? 'Хранилище недоступно: проверьте адрес, bucket и ключи доступа'
        : 'Каталог недоступен: проверьте путь и права на запись',
      hint: isS3
        ? 'Проверьте адрес сервера, имя bucket, регион и ключи доступа. Убедитесь, что сервер хранилища доступен с этого компьютера и что ключи выданы именно для этого bucket.'
        : 'Проверьте, что путь существует и что у пользователя, под которым работает приложение, есть право создавать в нём файлы.',
      detail: health.detail,
      checked,
    };
  }

  const key = `connection-test/${objectKey('txt')}`;
  const payload = Buffer.from('Проверка подключения edu-diary');

  try {
    await adapter.put({ key, body: payload, mimeType: 'text/plain' });
  } catch (error) {
    return {
      ok: false,
      step: 'write',
      message: isS3
        ? 'Запись не удалась: хранилище доступно, но файл не сохраняется'
        : 'Запись не удалась: каталог существует, но файл в нём не создаётся',
      hint: isS3
        ? 'Сервер отвечает, но запись запрещена. Проверьте права ключа доступа: ему нужно разрешение на запись объектов в этот bucket. Если bucket защищён политикой, добавьте в неё запись.'
        : 'Каталог найден, но файл в нём не создаётся. Проверьте права на запись и свободное место на диске.',
      detail: describe(error),
      checked,
    };
  }

  try {
    const stored = await adapter.get(key);
    if (stored === null || stored.body.toString('utf8') !== payload.toString('utf8')) {
      return {
        ok: false,
        step: 'read',
        message: 'Файл записался, но прочитать его обратно не удалось',
        hint: 'Запись работает, чтение — нет: проверьте права ключа доступа на чтение объектов. Без чтения учитель не увидит приложенный учеником файл.',
        detail: null,
        checked,
      };
    }
  } catch (error) {
    return {
      ok: false,
      step: 'read',
      message: 'Файл записался, но чтение не удалось',
      hint: 'Разрешите ключу доступа чтение объектов в этом bucket: иначе загруженные файлы не получится открыть.',
      detail: describe(error),
      checked,
    };
  }

  try {
    await adapter.remove(key);
  } catch (error) {
    /**
     * Удаление на работу не влияет: файлы мы всё равно не удаляем. Но сообщаем, потому что
     * это признак урезанных прав доступа.
     */
    return {
      ok: true,
      step: 'remove',
      message: 'Хранилище работает, но удалить пробный файл не удалось — проверьте права',
      hint: 'Работать можно: файлы мы не удаляем. Но если права урезаны, со временем в хранилище будет копиться мусор — стоит разрешить удаление.',
      detail: describe(error),
      checked,
    };
  }

  return {
    ok: true,
    step: 'done',
    message: 'Хранилище работает: запись, чтение и удаление',
    hint: 'Ничего делать не нужно. Если это внешнее хранилище — убедитесь, что оно находится на территории РФ (требование 152-ФЗ).',
    detail: health.detail,
    checked,
  };
}

/** Текст ошибки без значений ключей: они могут попасть в журнал и в отчёт. */
function describe(error: unknown): string {
  if (error instanceof Error) return `${error.name}: ${error.message}`;
  return String(error);
}
